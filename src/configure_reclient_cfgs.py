import importlib.util
import os
import re
import shutil
import subprocess
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.dirname(SCRIPT_DIR)
V8_DIR = os.path.join(os.path.dirname(ROOT_DIR), 'v8')
BUILDTOOLS_DIR = os.path.join(ROOT_DIR, 'buildtools')
RECLIENT_DIR = os.path.join(BUILDTOOLS_DIR, 'reclient')
RECLIENT_CFGS_DIR = os.path.join(BUILDTOOLS_DIR, 'reclient_cfgs')
REPROXY_CFG_PATH = os.path.join(RECLIENT_CFGS_DIR, 'reproxy.cfg')
DEFAULT_RBE_INSTANCE = 'projects/rbe-chrome-untrusted/instances/default_instance'

REPROXY_CFG_TEMPLATE = """# AUTOGENERATED FILE - DO NOT EDIT
# Generated by src/configure_reclient_cfgs.py
instance={rbe_instance}
service=remotebuildexecution.googleapis.com:443
log_format=reducedtext

{auth_flags}
fail_early_min_action_count=400
fail_early_min_fallback_ratio=0.5
deps_cache_max_mb=256
enable_deps_cache=true
experimental_goma_deps_cache=true
async_reproxy_termination=true
use_unified_uploads=true
fast_log_collection=true
depsscanner_address={depsscanner_address}

# Improve upload/download concurrency
max_concurrent_streams_per_conn=25
max_concurrent_requests_per_conn=25
min_grpc_connections=10
cas_concurrency=200

# Always compress artifacts
compression_threshold=0
use_batches=true

# Metric metadata
metrics_namespace={rbe_project}
"""


def get_clang_revision():
    update_py = os.path.join(V8_DIR, 'tools', 'clang', 'scripts', 'update.py')
    spec = importlib.util.spec_from_file_location('clang_update', update_py)
    if spec is None or spec.loader is None:
        raise RuntimeError(f'Unable to load clang update script: {update_py}')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.PACKAGE_VERSION


def normalize_rbe_instance(instance):
    if '/' not in instance:
        return f'projects/{instance}/instances/default_instance', instance
    m = re.fullmatch(r'projects/([-\w]+)/instances/[-\w]+', instance)
    if not m:
        raise ValueError(f'Invalid rbe_instance value: {instance}')
    return instance, m.group(1)


def generate_reproxy_cfg(rbe_instance, rbe_project):
    credshelper = os.path.join(RECLIENT_DIR, 'credshelper')
    depsscanner = os.path.join(RECLIENT_DIR, 'scandeps_server')
    if sys.platform.startswith('win'):
        depsscanner += '.exe'
        auth_flags = '# ADC auth flags\nuse_application_default_credentials=true\n'
    elif sys.platform == 'darwin':
        auth_flags = (
            'use_external_auth_token=true\n'
            f'credentials_helper={credshelper}\n'
            'credentials_helper_args=--auth_source=gcloud\n'
        )
    else:
        auth_flags = (
            '# Googler auth flags\n'
            f'credentials_helper={credshelper}\n'
            'credentials_helper_args=--auth_source=automaticAuth --gcert_refresh_timeout=20\n'
        )

    os.makedirs(RECLIENT_CFGS_DIR, exist_ok=True)
    content = REPROXY_CFG_TEMPLATE.format(
        rbe_instance=rbe_instance,
        rbe_project=rbe_project,
        auth_flags=auth_flags,
        depsscanner_address=f'exec://{depsscanner}',
    )
    with open(REPROXY_CFG_PATH, 'w') as f:
        f.write(content)


def main():
    if len(sys.argv) > 2:
        print(f'Usage: {sys.argv[0]} [rbe_instance]', file=sys.stderr)
        return 1

    raw_instance = sys.argv[1] if len(sys.argv) == 2 else DEFAULT_RBE_INSTANCE
    rbe_instance, rbe_project = normalize_rbe_instance(raw_instance)
    generate_reproxy_cfg(rbe_instance, rbe_project)

    clang_revision = get_clang_revision()
    pkg = f'infra_internal/rbe/reclient_cfgs/{rbe_project}/chromium-browser-clang'
    ensure_file = f'$ParanoidMode CheckIntegrity\n{pkg} revision/{clang_revision}\n'
    toolchain_root = os.path.join(RECLIENT_CFGS_DIR, 'chromium-browser-clang')
    cipd = shutil.which('cipd') or 'cipd'

    try:
        subprocess.check_output(
            [cipd, 'ensure', '-log-level=warning', '-root', toolchain_root, '-ensure-file', '-'],
            input=ensure_file,
            stderr=subprocess.STDOUT,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        auth = subprocess.run([cipd, 'auth-info'], capture_output=True, text=True, check=False)
        if auth.returncode != 0:
            print(
                'Access to remoteexec config CIPD package requires authentication.\n'
                'Please run `cipd auth-login` with your google.com credentials,\n'
                'or set `"download_reclient": False` in .gclient custom_vars.\n',
                flush=True,
            )
            return 1
        print(e.output, file=sys.stderr)
        return 1

    return 0


if __name__ == '__main__':
    sys.exit(main())
